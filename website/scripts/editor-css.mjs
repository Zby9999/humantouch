/**
 * The hero's editor wears the product's own styles: this bundles them from packages/humantouch/src/client (read
 * only, the product is not changed) into components/editor/editor-css.generated.ts, before the site runs or builds.
 */
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const client = fileURLToPath(new URL("../../packages/humantouch/src/client/", import.meta.url));
const result = await build({
  stdin: {
    contents: `export { styles } from "./styles"; export { toggleStyles } from "./toggle-styles";`,
    resolveDir: client,
    loader: "ts",
  },
  bundle: true,
  format: "esm",
  platform: "neutral",
  write: false,
});
const url = `data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString("base64")}`;
const { styles, toggleStyles } = await import(url);
// Comments out (they are the product's notes, not needed on the site), and the editor's own font named as the site loads it.
const css = (toggleStyles + styles)
  .replace(/\/\*[\s\S]*?\*\//g, "")
  .replace(/\n\s*\n/g, "\n")
  .replaceAll('"Human Touch Geist"', "var(--font-geist)");
/**
 * Until the product's own dark pass is merged (the front-end line, 2026-11-11; then take this out): the parts the
 * product draws in light colors in dark mode too, drawn dark here (designer, 2026-11-11). A row hovered in Layers as the
 * selected one's ground at 60%, as in light; a layer's disclosure and an effect's fold as the dark editor's raised tool; an instance's purple lighter, its name's ground a purple shade.
 */
const DARK_UNTIL_THE_PRODUCT = `
@media (prefers-color-scheme: dark) {
  .ht-shell { --ht-instance: #b87dff; --ht-instance-soft: rgb(154 60 238 / 0.28); }
  .ht-tree-row:hover { background: rgb(56 56 56 / 0.6); }
  :is(.ht-tree-chevron[data-open], .ht-fold) { background: #4a4a4a; box-shadow: 0 0 0 0.5px rgb(255 255 255 / 0.08), 0 1px 1.5px rgb(0 0 0 / 0.4); color: #e6e6e6; }
}
`;

/**
 * The product's dark colors follow the system's; on the site they follow the footer's theme too: each dark block is
 * kept for the system's dark unless the host says light, and given again for a host that says dark. The demos' shadow
 * hosts carry the page's `data-theme` (followSiteTheme).
 */
function followTheme(text) {
  const open = "@media (prefers-color-scheme: dark) {";
  let result = "";
  let at = 0;
  for (let start = text.indexOf(open); start !== -1; start = text.indexOf(open, at)) {
    let depth = 1;
    let end = start + open.length;
    while (depth > 0) {
      if (text[end] === "{") depth++;
      else if (text[end] === "}") depth--;
      end++;
    }
    const body = text.slice(start + open.length, end - 1);
    result += text.slice(at, start) + `${open} :host(:not([data-theme="light"])) {${body}} }\n:host([data-theme="dark"]) {${body}}`;
    at = end;
  }
  return result + text.slice(at);
}
const out = fileURLToPath(new URL("../components/editor/editor-css.generated.ts", import.meta.url));
writeFileSync(
  out,
  `// Generated by scripts/editor-css.mjs from the product's styles; not committed.\nexport const EDITOR_CSS = ${JSON.stringify(followTheme(css + DARK_UNTIL_THE_PRODUCT))};\n`,
);
console.log(`editor CSS: ${css.length} characters`);
